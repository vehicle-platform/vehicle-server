"""D-098 ride-summary record encoder (vehicle_server.ride_record) and its golden records."""

from __future__ import annotations

import math
import re

import pytest

from vehicle_server import ride_record
from vehicle_server.derived import golden, golden_records

RECORDS = ride_record.RECORDS


def _field(record: str, signal: str) -> dict:
    for f in RECORDS[record]["fields"].values():
        if f["signal"] == signal:
            return f
    raise KeyError(signal)


def _unit_field() -> tuple[str, dict]:
    """A field with resolution 1 and range_min 0 (exact ties)."""
    for rec, layout in RECORDS.items():
        for f in layout["fields"].values():
            if f["resolution"] == 1.0 and f["range_min"] == 0.0 and f["raw_max"] >= 10:
                return rec, f
    raise AssertionError("no unit field in the layout")


# --- layout (generated by defs) ------------------------------------------------------------


@pytest.mark.parametrize("name", list(RECORDS))
def test_layout_is_contiguous_and_na_is_all_ones(name):
    rec = RECORDS[name]
    assert rec["layout_version"] == ride_record.LAYOUT_VERSION
    pos = ride_record.HEADER_LENGTH
    for f in rec["fields"].values():
        assert f["byte"] == pos
        assert f["length"] in (1, 2, 4)
        assert f["na"] == (1 << (8 * f["length"])) - 1
        assert 0 < f["raw_max"] < f["na"]
        pos += f["length"]
    assert pos == rec["length"]


def test_python_layout_matches_the_c_tables():
    rows = golden_records.field_rows()  # raises when the C table order differs
    header = (golden.DEFS_C_RT_CORE / "platform_uds.h").read_text()

    def macro(name: str) -> int:
        m = re.search(rf"#define PLATFORM_UDS_{name} \((0x[0-9A-Fa-f]+|\d+)u\)", header)
        assert m, name
        return int(m.group(1), 0)

    assert macro("RIDE_FIELD_COUNT") == len(rows)
    assert macro("RIDE_RECORD_LAYOUT_VERSION") == ride_record.LAYOUT_VERSION
    for name, rec in RECORDS.items():
        assert macro(f"DID_{name}") == rec["did"]
        assert macro(f"DID_{name}_LENGTH") == rec["length"]
    for rec, fname, f in rows:
        base = f"{rec}_{fname}"
        assert macro(f"{base}_BYTE") == f["byte"]
        assert macro(f"{base}_LENGTH") == f["length"]
        assert macro(f"{base}_MAX") == f["raw_max"]
        assert macro(f"{base}_NA") == f["na"]


# --- field encoding ------------------------------------------------------------------------


def test_half_to_even_ties():
    _, f = _unit_field()
    assert [ride_record.field_raw(f, v) for v in (0.5, 1.5, 2.5, 3.5, 4.4, 4.6)] == [
        0,
        2,
        2,
        4,
        4,
        5,
    ]


def test_out_of_range_missing_and_non_finite_read_not_available():
    _, f = _unit_field()
    na, top = f["na"], f["raw_max"]
    assert ride_record.field_raw(f, float(top)) == top
    assert ride_record.field_raw(f, top + 0.4) == top  # rounds into the range
    assert ride_record.field_raw(f, top + 1.0) == na  # never clamped
    assert ride_record.field_raw(f, -0.4) == 0
    assert ride_record.field_raw(f, -1.0) == na
    for bad in (None, math.nan, math.inf, -math.inf, 1e40):
        assert ride_record.field_raw(f, bad) == na


def test_quotient_is_float32():
    f = _field("RIDE_USAGE", "ride_distance")  # resolution 0.01
    for v in (0.015, 12.345, 1999.99):
        q = ride_record.quotient(f, v)
        assert ride_record.f32(q) == q


def test_offset_by_range_min():
    for layout in RECORDS.values():
        for f in layout["fields"].values():
            if f["range_min"] < 0:
                assert ride_record.field_raw(f, f["range_min"]) == 0
                assert ride_record.field_raw(f, 0.0) == round(-f["range_min"] / f["resolution"])
                return
    pytest.skip("no signed field in the layout")


# --- records -------------------------------------------------------------------------------


def test_header_and_round_trip():
    name = "RIDE_USAGE"
    values = {"ride_distance": 12.34, "ride_time": 600.0, "ride_stop_count": None}
    data = ride_record.encode(name, values, counter=0x1234, closed=True)
    assert len(data) == RECORDS[name]["length"]
    assert data[:4] == bytes([ride_record.LAYOUT_VERSION, 0x12, 0x34, 0x01])
    dec = ride_record.decode(name, data)
    assert (dec.layout_version, dec.counter, dec.closed) == (1, 0x1234, True)
    assert dec.values["ride_distance"] == pytest.approx(12.34)
    assert dec.values["ride_time"] == 600.0
    assert dec.values["ride_stop_count"] is None  # given as None
    assert dec.values["ride_idle_time"] is None  # absent


def test_no_ride_closed_is_all_not_available():
    for name, rec in RECORDS.items():
        data = ride_record.encode(name, {}, counter=0, closed=False)
        assert data[:4] == bytes([1, 0, 0, 0])
        assert data[4:] == b"\xff" * (rec["length"] - 4)
    # values are ignored while no ride is closed
    data = ride_record.encode("RIDE_USAGE", {"ride_time": 5.0}, counter=7, closed=False)
    assert ride_record.decode("RIDE_USAGE", data).values["ride_time"] is None


def test_counter_ffff_is_valid_and_bounds_are_checked():
    data = ride_record.encode("RIDE_USAGE", {}, counter=0xFFFF, closed=True)
    assert data[1:3] == b"\xff\xff"
    with pytest.raises(ValueError):
        ride_record.encode("RIDE_USAGE", {}, counter=0x10000, closed=True)
    with pytest.raises(ValueError):
        ride_record.encode("RIDE_USAGE", {"ride_fuel_used": 1.0}, counter=1, closed=True)
    with pytest.raises(ValueError):
        ride_record.decode("RIDE_USAGE", b"\x00" * 3)


