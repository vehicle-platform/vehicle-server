@pytest.fixture(scope="module")
def generated():
    return golden.generate()


def test_records_header_is_generated(generated):
    names = [f.name for f in generated.files]
    assert names[-1] == golden_records.RECORDS_HEADER
    text = generated.files[-1].text
    assert "derived_ride_field_vectors[]" in text
    assert "derived_no_ride_records[]" in text
    assert "tie 2.5" in text and "tie 3.5" in text


def test_golden_records_carry_the_class_b_values(generated):
    selected = set(generated.class_b.selected)
    specs = golden_b_specs()
    for scenario, rides in generated.class_b.ride_values.items():
        for ride, rows in enumerate(rides):
            expected = {r.signal: (r.value if r.valid else None) for r in rows}
            for name in RECORDS:
                vals = {s: v for s, v in expected.items() if s in ride_record.signals(name)}
                data = ride_record.encode(name, vals, counter=ride + 1, closed=True)
                dec = ride_record.decode(name, data)
                assert (dec.counter, dec.closed) == (ride + 1, True)
                for signal, value in dec.values.items():
                    if signal not in selected or expected.get(signal) is None:
                        assert value is None, (scenario, ride, signal)
                        continue
                    tol = specs[signal]["resolution"] / 2 + 1e-9
                    assert value == pytest.approx(expected[signal], abs=tol), (scenario, signal)


def golden_b_specs():
    from vehicle_server.defs import vehicle_derived

    return vehicle_derived.SIGNALS
