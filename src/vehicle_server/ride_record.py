"""Raw encoder (and decoder) of the ride-summary record DIDs 0xFD40-0xFD4E (D-098).

The layout is generated by vehicle-defs (`vehicle_defs.uds.RIDE_RECORDS`, the same codegen
run that writes rt-core's `platform_uds_ride_fields[]`); nothing here is typed by hand.

Record = 4-byte header + big-endian unsigned fields:

    byte 0      layout version (`RIDE_RECORD_LAYOUT_VERSION`)
    bytes 1-2   stop-epoch counter of the closed ride (a change detector, every value valid)
    byte 3      bit 0 RIDE_CLOSED (0 = no ride closed since boot: every field NOT_AVAILABLE),
                bits 1-7 zero
    fields      raw = round_half_even((value - range_min) / resolution)

The arithmetic is the one rt-core's generic writer runs (D-098 item 5): `value`, `range_min`
and `resolution` are float32, the subtraction and the division are float32 operations, and
the quotient is rounded half to even (`lrintf` with the default FE_TONEAREST, never
`roundf`/`lroundf`). A float32 operation is emulated exactly by rounding the double result of
float32 operands to float32 (double carries more than 2 * 24 + 2 bits).

NOT_AVAILABLE (D-098 item 3) is the all-ones value of the field width. A field reads
NOT_AVAILABLE when the value is missing (None), not finite, or its rounded raw value is below
0 or above `raw_max` (out of range: never clamped, D-070). Pure: no I/O.
"""

from __future__ import annotations

import math
import struct
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from vehicle_server.defs import uds

RECORDS: Mapping[str, Mapping[str, Any]] = uds.RIDE_RECORDS
LAYOUT_VERSION: int = uds.RIDE_RECORD_LAYOUT_VERSION
HEADER_LENGTH = 4
RIDE_CLOSED_BIT = 0x01
COUNTER_MAX = 0xFFFF


def f32(x: float) -> float:
    """x rounded to the nearest float32 (inf stays inf, nan stays nan)."""
    if math.isnan(x):
        return x
    try:
        return struct.unpack("<f", struct.pack("<f", x))[0]
    except OverflowError:
        return math.copysign(math.inf, x)


def quotient(field: Mapping[str, Any], value: float) -> float:
    """(value - range_min) / resolution in float32, as the rt-core writer computes it."""
    diff = f32(f32(value) - f32(field["range_min"]))
    return f32(diff / f32(field["resolution"]))


def field_raw(field: Mapping[str, Any], value: float | None) -> int:
    """The raw value of one field, or its `na` (all ones) when NOT_AVAILABLE."""
    if value is None or not math.isfinite(value):
        return field["na"]
    x = quotient(field, value)
    if not math.isfinite(x):
        return field["na"]
    raw = round(x)  # Python round on a float: half to even, exact
    if raw < 0 or raw > field["raw_max"]:
        return field["na"]
    return raw


def field_value(field: Mapping[str, Any], raw: int) -> float | None:
    """The physical value of a raw field (None for NOT_AVAILABLE or above raw_max)."""
    if raw == field["na"] or raw > field["raw_max"]:
        return None
    return field["range_min"] + raw * field["resolution"]


def signals(name: str) -> list[str]:
    """The derived signals carried by a record, in field order."""
    return [f["signal"] for f in RECORDS[name]["fields"].values()]


def encode(
    name: str,
    values: Mapping[str, float | None],
    *,
    counter: int,
    closed: bool,
) -> bytes:
    """The data record of DID `RECORDS[name]["did"]` (without the 0x62 DID echo).

    `values` maps derived-signal names to the closed ride's values (float or None); a signal
    of the record that is absent reads NOT_AVAILABLE. With `closed` False every field is
    NOT_AVAILABLE whatever `values` holds (no ride closed since boot).
    """
    rec = RECORDS[name]
    if not 0 <= counter <= COUNTER_MAX:
        raise ValueError(f"ride counter {counter} outside 0..{COUNTER_MAX}")
    known = set(signals(name))
    unknown = sorted(set(values) - known)
    if unknown:
        raise ValueError(f"{name}: signals not in the record: {unknown}")
    out = bytearray(rec["length"])
    hdr = rec["header"]
    out[hdr["LAYOUT_VERSION"]["byte"]] = rec["layout_version"]
    c = hdr["RIDE_COUNTER"]["byte"]
    out[c : c + 2] = counter.to_bytes(2, "big")
    if closed:
        out[hdr["RIDE_CLOSED"]["byte"]] |= hdr["RIDE_CLOSED"]["mask"]
    for field in rec["fields"].values():
        raw = field_raw(field, values.get(field["signal"])) if closed else field["na"]
        b, n = field["byte"], field["length"]
        out[b : b + n] = raw.to_bytes(n, "big")
    return bytes(out)


@dataclass(frozen=True)
class Decoded:
    layout_version: int
    counter: int
    closed: bool
    raw: dict[str, int]  # signal -> raw (na included)
    values: dict[str, float | None]  # signal -> physical value, None = NOT_AVAILABLE


def decode(name: str, data: bytes) -> Decoded:
    """Inverse of `encode` (for tests and host tools); raises on a wrong length."""
    rec = RECORDS[name]
    if len(data) != rec["length"]:
        raise ValueError(f"{name}: {len(data)} bytes, expected {rec['length']}")
    hdr = rec["header"]
    c = hdr["RIDE_COUNTER"]["byte"]
    raw: dict[str, int] = {}
    values: dict[str, float | None] = {}
    for field in rec["fields"].values():
        b, n = field["byte"], field["length"]
        r = int.from_bytes(data[b : b + n], "big")
        raw[field["signal"]] = r
        values[field["signal"]] = field_value(field, r)
    return Decoded(
        layout_version=data[hdr["LAYOUT_VERSION"]["byte"]],
        counter=int.from_bytes(data[c : c + 2], "big"),
        closed=bool(data[hdr["RIDE_CLOSED"]["byte"]] & hdr["RIDE_CLOSED"]["mask"]),
        raw=raw,
        values=values,
    )
